#pragma once

// ============================================================================
// どの描画（シェーダー）を通すかの設定。シーンごとに決める。
//
// このエンジンには6組のシェーダーが入っている。
//   Object3d      物を描く          … どのシーンでも要る
//   Text          文字を描く        … どのシーンでも要る
//   Line          線を描く          … 当たり判定の枠（SetShowColliders）
//   Draw2D        2Dの図形と絵      … 積まれたときだけ通る
//   Particle      粒（パーティクル）… 出したときだけ通る
//   Shadow        地面へ落とす影    … 要らないシーンがある
//
// 影は「見た目の好み」であって、エンジンの機能ではない。
// ここは「そのシーンが何を通したいか」を1か所に集めた設定。
//
// ■ 使う側
//   engine.Features().shadows = false;         // 影を落とさない
// ============================================================================

struct RenderFeatures {
    // 地面へ落とす影（Shadow.*.hlsl）。
    // 平らな床の上に置くものが多いシーンでは、位置が分かりやすくなるので既定はON。
    // 床が無いシーンでは、影だけが宙に出て邪魔になるので切る
    bool shadows = true;
};
